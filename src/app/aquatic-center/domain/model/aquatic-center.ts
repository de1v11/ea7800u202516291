export class AquaticCenter {

  name : string
  activityType : string
  capacity : string
  latitude : string
  longitude : string



  constructor(name: string, activityType: string, capacity: string, latitude: string, longitude: string) {
    this.name = name;
    this.activityType = activityType;
    this.capacity = capacity;
    this.latitude = latitude;
    this.longitude = longitude;
  }
}


